#!/usr/bin/env node
// Copies the compiled ABIs into shared/src/abi.ts so the agent and the web app stay in sync.
// Usage: node tools/export-abi.mjs   (after `forge build`)
import { readFileSync, writeFileSync } from "node:fs";

const names = ["LeashVault", "PayeeRegistry"];
let out = "// Generated by tools/export-abi.mjs from contracts/out. Do not edit by hand.\n\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync("shared/src/abi.ts", out);

// Creation bytecode, so the web app can deploy from the browser with the user's own wallet.
let bc = "// Generated by tools/export-abi.mjs from contracts/out. Do not edit by hand.\n\n";
for (const n of names) {
  const { bytecode } = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
  bc += `export const ${n[0].toLowerCase()}${n.slice(1)}Bytecode = "${bytecode.object}" as const;\n`;
}
writeFileSync("web/src/lib/bytecode.ts", bc);
console.log(`✓ wrote shared/src/abi.ts and web/src/lib/bytecode.ts (${names.join(", ")})`);
